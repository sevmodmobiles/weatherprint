    /**
     * Фраза для [date]. [used] — погодные фразы, уже напечатанные в этом году.
     * Результат зависит только от даты, погоды и [used] — в предпросмотре и на печати одинаковый.
     */
    fun forDay(w: Weather, used: Set<String>, date: LocalDate = LocalDate.now()): String {
        val temp = w.days.firstOrNull()?.let { (it.tMin + it.tMax) / 2 } ?: w.temp
        val special = when {
            w.code >= 95 -> storm
            temp <= -10 -> cold
            w.code in 68..77 || w.code in 85..86 -> snow
            w.code in 51..67 || w.code in 80..82 -> rain
            temp >= 25 -> hot
            w.code <= 1 -> sun
            w.code == 3 || w.code == 45 || w.code == 48 -> gloomy
            else -> null
        }
        if (special != null && date.toEpochDay() % 3 == 0L) {
            special.firstOrNull { it !in used }?.let { return it }
        }
        return general[(date.dayOfYear - 1) % general.size]
    }

    /** Погодная ли фраза — такие запоминаем, чтобы не повторять. */
    fun isWeather(phrase: String) = phrase !in general
