    fun forDay(w: Weather, date: LocalDate = LocalDate.now()): String {
        val day = date.toEpochDay()
        val temp = w.days.firstOrNull()?.let { (it.tMin + it.tMax) / 2 } ?: w.temp
        val special = when {
            w.code >= 95 -> storm
            temp <= -10 -> cold
            w.code in 68..77 || w.code in 85..86 -> snow
            w.code in 51..67 || w.code in 80..82 -> rain
            temp >= 25 -> hot
            w.code <= 1 -> sun
            w.code == 3 || w.code == 45 || w.code == 48 -> gloomy
            else -> null
        }
        return if (special != null && day % 3 == 0L) special[((day / 3) % special.size).toInt()]
        else general[(day % general.size).toInt()]
    }
